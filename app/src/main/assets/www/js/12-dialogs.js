function showAppHint(key){
  const item=APP_HINTS[String(key||'')];
  if(!item)return;
  const backdrop=document.getElementById('aiHintBackdrop');
  const title=document.getElementById('aiHintTitle');
  const text=document.getElementById('aiHintText');
  if(!backdrop||!title||!text)return;
  title.textContent=item.title||'Подсказка';
  text.textContent=item.text||'';
  backdrop.classList.add('open');
}
function showAiHint(key){showAppHint(key)}
function closeAiHint(){
  const backdrop=document.getElementById('aiHintBackdrop');
  if(backdrop)backdrop.classList.remove('open');
}
function aiHintBackdropClick(event){
  if(event.target&&event.target.id==='aiHintBackdrop')closeAiHint();
}
